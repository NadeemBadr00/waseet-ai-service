#!/usr/bin/env node
// Functional smoke test for a running waseet-ai-service revision.
//
//   WASEET_AI_CLIENT_ID=... WASEET_AI_CLIENT_SECRET=... WASEET_AI_ENVIRONMENT=dev \
//     node scripts/smoke-ai-contract.mjs --base-url=https://<service> [--only=bio,help] [--expect=new|current] [--json]
//
// - Uses the signed token exchange (/v1/auth/token). The secret is read from the environment only and is never printed; tokens and long opaque strings are redacted from every output.
// - Every request carries a VALID body, and a 400 is a FAILURE (it is not a functional success). The response shape AND content are checked.
// - Only stateless endpoints are called: nothing is stored, no user data is read or written, nothing is sent to users.
// - Each result is classified: MODEL (generated by the model), COMPUTED (server-side arithmetic / ranking, no model), FALLBACK (the response says a fallback was used), or FAIL.
// - --expect=new additionally requires behaviour introduced by the integration branch (attachments read by the accreditation review, the rubric, marketplace score basis).
import { pathToFileURL } from "node:url";

const redact = (value) => String(value).replace(/[A-Za-z0-9_\-.]{32,}/g, "<redacted>");
const sleepless = (ms) => AbortSignal.timeout(ms);

export async function runSmoke({ baseUrl, clientId, clientSecret, environment = "dev", only = [], expect = "current", fetchImpl = globalThis.fetch }) {
  const base = baseUrl.replace(/\/+$/, "");
  const results = [];
  const want = (name) => !only.length || only.some((item) => name.startsWith(item));
  const add = (name, path, status, kind, ok, note) => results.push({ name, path, status, kind: ok ? kind : "FAIL", ok, note: redact(note ?? "") });

  const call = async (path, { method = "POST", body, headers = {}, timeoutMs = 60000, raw = false } = {}) => {
    const started = Date.now();
    try {
      const res = await fetchImpl(base + path, { method, headers: { "content-type": "application/json", ...headers }, body: body === undefined ? undefined : JSON.stringify(body), signal: sleepless(timeoutMs) });
      const text = await res.text();
      let json = null;
      if (!raw) { try { json = JSON.parse(text); } catch { json = null; } }
      return { status: res.status, text, json, ms: Date.now() - started, contentType: res.headers.get("content-type") ?? "" };
    } catch (error) {
      return { status: 0, text: "", json: null, ms: Date.now() - started, error: error?.cause?.code ?? error?.message ?? "network error" };
    }
  };

  // ── health + auth ──
  const health = await call("/health", { method: "GET", timeoutMs: 20000 });
  add("health", "/health", health.status, "COMPUTED", health.status === 200 && health.json?.status === "healthy", health.json ? `service=${health.json.service} version=${health.json.version}` : health.error);
  const noAuth = await call("/v1/ai/profile/performance-summary", { body: {}, timeoutMs: 20000 });
  add("auth.required", "/v1/ai/profile/performance-summary", noAuth.status, "COMPUTED", noAuth.status === 401 && noAuth.json?.error?.code === "AUTH_REQUIRED", "a request without a token is refused");
  const badAuth = await call("/v1/ai/profile/performance-summary", { body: {}, headers: { authorization: "Bearer not-a-real-token-" + "x".repeat(8) }, timeoutMs: 20000 });
  add("auth.invalid", "/v1/ai/profile/performance-summary", badAuth.status, "COMPUTED", badAuth.status === 401, "an arbitrary token is refused");

  const exchange = await call("/v1/auth/token", { body: { clientId, clientSecret, environment, actor: { userId: "smoke-test", role: "system" } }, timeoutMs: 20000 });
  const token = (exchange.json?.data ?? exchange.json)?.token;
  add("auth.token", "/v1/auth/token", exchange.status, "COMPUTED", exchange.status === 200 && typeof token === "string" && token.length > 20, token ? "signed token issued (not printed)" : "no token issued");
  if (!token) return finish(results, base);
  const auth = { authorization: `Bearer ${token}` };
  const post = (path, body, opts = {}) => call(path, { body, headers: auth, ...opts });
  const isString = (value, min = 1) => typeof value === "string" && value.trim().length >= min;
  const data = (r) => r.json?.data ?? r.json ?? {};

  // ── capabilities ──
  if (want("capabilities")) {
    const r = await call("/v1/ai/capabilities", { method: "GET", headers: auth, timeoutMs: 20000 });
    const models = data(r).models;
    add("capabilities", "/v1/ai/capabilities", r.status, "COMPUTED", r.status === 200 && Array.isArray(models) && models.length > 0, `models=${Array.isArray(models) ? models.length : "n/a"} defaultText=${data(r).defaultTextModel}`);
  }

  // ── provider profile ──
  if (want("perf")) {
    const r = await post("/v1/ai/profile/performance-summary", { providerId: "smoke", totalProjectsCompleted: 4, onTimeProjectsCount: 3, totalClientsCount: 3, repeatClientsCount: 1 });
    add("perf.summary", "/v1/ai/profile/performance-summary", r.status, "COMPUTED", r.status === 200 && data(r).onTimeDelivery === 75, `onTimeDelivery=${data(r).onTimeDelivery} (3 of 4 = 75; no model involved)`);
  }
  if (want("bio")) {
    const source = "مصمم جرافيك لدي خبرة سنتين في تصميم الهوية البصرية";
    for (const [name, path] of [["bio.enhance", "/v1/ai/profile/bio/enhance"], ["bio.enhance-alias", "/v1/ai/profile/enhance-bio"], ["bio.bio-enhance-alias", "/v1/ai/profile/bio-enhance"]]) {
      const r = await post(path, { providerId: "smoke", bio: source, specialties: ["تصميم"], subSpecialties: [], maxLength: 300 });
      if (name === "bio.bio-enhance-alias" && expect !== "new" && r.status === 404) { results.push({ name, path, status: 404, kind: "INFO", ok: true, note: "alias introduced by the integration branch: 404 is expected on a revision that predates it (--expect=new requires it)" }); continue; }
      const bio = data(r).suggestedBio;
      const grounded = isString(bio, 10) && !/\b99\b/.test(bio) && bio.trim() !== source;
      add(name, path, r.status, "MODEL", r.status === 200 && grounded, r.status === 200 ? `${bio?.length ?? 0} chars, rewritten (not an echo), no invented years` : `status ${r.status} ${r.json?.error?.code ?? r.error ?? ""}`);
    }
    const s = await post("/v1/ai/profile/skills", { providerId: "smoke", specialtyName: "تصميم جرافيك", existingSkills: [] });
    add("bio.skills", "/v1/ai/profile/skills", s.status, "MODEL", s.status === 200 && Array.isArray(data(s).suggestedSkills) && data(s).suggestedSkills.length > 0 && data(s).suggestedSkills.every((x) => isString(x)), `${data(s).suggestedSkills?.length ?? 0} skills`);
  }

  // ── proposals + client request ──
  if (want("proposal")) {
    const r = await post("/v1/ai/proposals/suggest", { projectId: "smoke", currentTitle: "تصميم هوية بصرية", currentMessage: "سأسلّم الشعار ودليل الاستخدام خلال أسبوعين", currency: "USD" });
    add("proposal.suggest", "/v1/ai/proposals/suggest", r.status, "MODEL", r.status === 200 && isString(data(r).suggestedTitle) && typeof data(r).qualityScore === "number", `title ok=${isString(data(r).suggestedTitle)} score=${data(r).qualityScore}`);
    const empty = await post("/v1/ai/proposals/suggest", { projectId: "smoke", currentTitle: "   ", currentMessage: "" });
    add("proposal.empty-draft-refused", "/v1/ai/proposals/suggest", empty.status, "COMPUTED", empty.status === 422, "an empty draft is refused with 422 (this is the EXPECTED answer, not a 400-as-success)");
  }
  if (want("budget")) {
    const body = { title: "تطوير متجر إلكتروني متكامل", description: "بناء واجهة متجر ولوحة تحكم مع بوابة دفع", specialtyName: "تطوير المواقع", deliveryDays: 21, currency: "USD" };
    for (const [name, path] of [["budget.milestones", "/v1/ai/client/requests/budget-milestones"], ["budget.alias", "/v1/ai/budget-milestones"]]) {
      const r = await post(path, body);
      const d = data(r); const sum = Array.isArray(d.suggestedMilestones) ? d.suggestedMilestones.reduce((total, m) => total + Number(m.pct), 0) : NaN;
      const ok = r.status === 200 && Number(d.recommendedMinBudget) > 0 && Number(d.recommendedMaxBudget) >= Number(d.recommendedMinBudget) && sum === 100 && d.suggestedDurationDays === 21;
      add(name, path, r.status, "MODEL", ok, r.status === 200 ? `budget ${d.recommendedMinBudget}-${d.recommendedMaxBudget} stages=${d.suggestedMilestones?.length} pct=${sum} days=${d.suggestedDurationDays}` : `status ${r.status} ${r.json?.error?.code ?? r.error ?? ""}`);
    }
  }

  // ── marketplace (ranking is deterministic; it must say so) ──
  if (want("market")) {
    const candidates = [
      { id: "a", title: "تصميم شعار احترافي", description: "هوية بصرية", category: "design", categoryLabel: "التصميم" },
      { id: "b", title: "برمجة متجر", description: "متجر إلكتروني", category: "web", categoryLabel: "تطوير المواقع" },
    ];
    const r = await post("/v1/ai/marketplace/recommendations", { query: "تصميم شعار", limit: 5, candidates });
    const items = data(r).items ?? [];
    const deterministic = items.every((item) => item.generationSource === "DETERMINISTIC");
    let ok = r.status === 200 && items[0]?.id === "a" && deterministic;
    let note = `top=${items[0]?.id} source=${items[0]?.generationSource} score=${items[0]?.matchScore}`;
    if (expect === "new") { ok = ok && items[0]?.scoreBasis === "QUERY_TERM_OVERLAP"; note += ` basis=${items[0]?.scoreBasis}`; }
    add("market.recommendations", "/v1/ai/marketplace/recommendations", r.status, "COMPUTED", ok, note + (deterministic ? " (keyword ranking, not AI)" : ""));
  }

  // ── help assistant (SSE) ──
  if (want("help")) {
    const r = await post("/v1/ai/help/chat", { question: "ما هو الضمان المالي في وسيط؟", language: "ar", dialect: "saudi", history: [] }, { raw: true });
    const events = [...r.text.matchAll(/event: ([^\n]+)\ndata: ([^\n]*)/g)].map((m) => ({ event: m[1], data: (() => { try { return JSON.parse(m[2]); } catch { return {}; } })() }));
    const chunks = events.filter((e) => e.event === "help:answer_chunk").map((e) => e.data.chunk ?? "").join("");
    const started = events.find((e) => e.event === "help:answer_start")?.data ?? {};
    const failed = events.some((e) => e.event === "help:error");
    const ok = r.status === 200 && !failed && events.some((e) => e.event === "help:answer_start") && /[؀-ۿ]/.test(chunks) && chunks.length > 30 && events.some((e) => e.event === "help:answer_complete");
    add("help.chat", "/v1/ai/help/chat", r.status, started.knowledgeFallback ? "FALLBACK" : "MODEL", ok, `events=${events.length} answer=${chunks.length} chars knowledgeFallback=${started.knowledgeFallback === true} mode=${started.mode}`);
  }

  // ── voice: TTS, then the SAME audio through STT (also covers MIME parameters) ──
  let spoken = null;
  if (want("voice") || want("tts") || want("stt")) {
    const t = await post("/v1/ai/tts/synthesize", { text: "مرحبا بك في وسيط", voice: "Puck", dialect: "saudi", mimeType: "audio/wav" });
    const audio = data(t).audio ?? {};
    const bytes = isString(audio.base64Audio) ? Buffer.from(audio.base64Audio, "base64") : Buffer.alloc(0);
    const wav = bytes.length > 1000 && bytes.toString("ascii", 0, 4) === "RIFF" && bytes.toString("ascii", 8, 12) === "WAVE";
    const model = data(t).metadata?.modelUsed;
    add("voice.tts", "/v1/ai/tts/synthesize", t.status, "MODEL", t.status === 200 && wav && /gemini/i.test(String(model)), `wav=${wav} bytes=${bytes.length} model=${model} dialect=${data(t).metadata?.dialect}`);
    if (wav) spoken = audio.base64Audio;
  }
  if (spoken && (want("voice") || want("stt"))) {
    for (const [name, mime] of [["voice.stt", "audio/wav"], ["voice.stt-mime-params", "audio/wav; codecs=1"]]) {
      const r = await post("/v1/ai/stt/transcribe", { audioBase64: spoken, mimeType: mime, languageCodes: ["ar-SA"] }, { timeoutMs: 90000 });
      const text = data(r).text;
      add(name, "/v1/ai/stt/transcribe", r.status, "MODEL", r.status === 200 && isString(text) && /[؀-ۿ]/.test(text), `transcript=${isString(text) ? text.length + " chars" : "none"} model=${data(r).model} (${mime})`);
    }
  }

  // ── identity (synthetic 1x1 image: the contract must hold, nothing may be claimed as a match) ──
  if (want("identity")) {
    const png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==";
    const r = await post("/v1/ai/identity/compare-fields", { image: { mimeType: "image/png", data: png }, declared: { name: "اختبار", birthDate: "1990-01-01", nationalId: "1000000000" } });
    const fields = data(r).fields ?? {};
    const allowed = ["MATCH", "MISMATCH", "UNREADABLE"];
    const shape = ["name", "birthDate", "nationalId"].every((k) => allowed.includes(fields[k]));
    const noFalseMatch = ["name", "birthDate", "nationalId"].every((k) => fields[k] !== "MATCH");
    add("identity.compare-fields", "/v1/ai/identity/compare-fields", r.status, "MODEL", r.status === 200 && shape && noFalseMatch, `fields=${JSON.stringify(fields)} (a blank image must never MATCH)`);
  }

  // ── accreditation: synthetic evidence ──
  if (want("accreditation")) {
    const text = "export function checkout(cart) { return cart.items.reduce((sum, item) => sum + item.price * item.qty, 0); }\n// unit tests for discounts and tax";
    const dataUri = `data:text/plain;base64,${Buffer.from(text).toString("base64")}`;
    const withEvidence = await post("/v1/ai/accreditation-review", { sampleId: "smoke-1", title: "نظام سلة", description: "سلة شراء مع اختبارات", technologiesUsed: ["TypeScript"], specialtyName: "تطوير مواقع", attachments: [dataUri] }, { timeoutMs: 90000 });
    const d = data(withEvidence);
    const noEvidence = await post("/v1/ai/accreditation-review", { sampleId: "smoke-2", title: "نظام سلة", description: "متجر إلكتروني كامل بواجهة ولوحة تحكم وبوابة دفع", technologiesUsed: ["React"], specialtyName: "تطوير مواقع" }, { timeoutMs: 90000 });
    const n = data(noEvidence);
    const noScoreWithoutEvidence = n.aiScore == null || n.inspected === true; // a description alone is never turned into a quality score
    if (expect === "new") {
      add("accreditation.with-evidence", "/v1/ai/accreditation-review", withEvidence.status, "MODEL", withEvidence.status === 200 && d.inspected === true && typeof d.aiScore === "number" && Array.isArray(d.rubric?.criteria) && d.humanReviewRequired === true, `inspected=${d.inspected} score=${d.aiScore} rubric=${d.rubric?.version} humanReviewRequired=${d.humanReviewRequired}`);
      add("accreditation.no-evidence", "/v1/ai/accreditation-review", noEvidence.status, "MODEL", noEvidence.status === 200 && n.aiScore === null && n.aiQualityRating === null && n.humanReviewRequired === true, `score=${n.aiScore} rating=${n.aiQualityRating} basis=${n.basis}`);
    } else {
      add("accreditation.current-behaviour", "/v1/ai/accreditation-review", withEvidence.status, "MODEL", withEvidence.status === 200 && (d.evaluation || d.feedback) !== undefined, `attachmentsHonoured=${d.inspected === true && d.evidence?.some?.((e) => e.contentRead)} (informational) score=${d.aiScore} basis=${d.basis}; description-only score=${n.aiScore} (${noScoreWithoutEvidence ? "no score from a description alone" : "SCORE FROM A DESCRIPTION ALONE"})`);
    }
  }
  return finish(results, base);
}

function finish(results, base) {
  return { base, results, failed: results.filter((r) => !r.ok).length, passed: results.filter((r) => r.ok).length };
}

function parseArgs(argv) {
  const out = { only: [], expect: "current", json: false };
  for (const arg of argv) {
    const [key, value = ""] = arg.replace(/^--/, "").split("=");
    if (key === "base-url") out.baseUrl = value;
    else if (key === "only") out.only = value.split(",").filter(Boolean);
    else if (key === "expect") out.expect = value === "new" ? "new" : "current";
    else if (key === "json") out.json = true;
  }
  return out;
}

export async function main(argv, env = process.env) {
  const args = parseArgs(argv);
  const clientSecret = env.WASEET_AI_CLIENT_SECRET;
  if (!args.baseUrl || !clientSecret) { console.error("usage: WASEET_AI_CLIENT_SECRET=... [WASEET_AI_CLIENT_ID] [WASEET_AI_ENVIRONMENT] node scripts/smoke-ai-contract.mjs --base-url=https://service [--only=a,b] [--expect=new|current] [--json]"); return 2; }
  const summary = await runSmoke({ baseUrl: args.baseUrl, clientId: env.WASEET_AI_CLIENT_ID || "waseet_core_backend", clientSecret, environment: env.WASEET_AI_ENVIRONMENT || "dev", only: args.only, expect: args.expect });
  if (args.json) console.log(JSON.stringify(summary, null, 2));
  else {
    for (const r of summary.results) console.log(`${r.ok ? "PASS" : "FAIL"}  ${r.kind.padEnd(8)} ${String(r.status).padEnd(4)} ${r.name.padEnd(30)} ${r.note}`);
    console.log(`\n${summary.passed} passed, ${summary.failed} failed  (${summary.base})`);
  }
  return summary.failed ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exit(await main(process.argv.slice(2)));
