describe("route backward compatibility", () => {
  const app = buildApp();
  before(async () => { paidFixture(); await app.ready(); });
  after(async () => { await app.close(); });

  test(`all ${MAIN_ROUTES.length} routes of main are still registered`, () => {
    const missing = MAIN_ROUTES.filter(([method, url]) => !app.hasRoute({ method: method as "GET", url }));
    assert.deepEqual(missing, []);
  });

  test("the aliases callers rely on are present", () => {
    for (const url of ["/v1/ai/profile/enhance-bio", "/v1/ai/profile/bio-enhance", "/v1/ai/profile/bio/enhance", "/v1/ai/budget-milestones", "/v1/ai/client/requests/budget-milestones"]) {
      assert.equal(app.hasRoute({ method: "POST", url }), true, url);
    }
  });
});
